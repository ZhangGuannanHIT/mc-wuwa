package cn.zgnhit.mcwuwa.content.mechanics;

import java.util.Map;
import java.util.Set;
import static cn.zgnhit.mcwuwa.content.mechanics.MechanicsEngine.*;
import static cn.zgnhit.mcwuwa.content.mechanics.ExtendedMechanics.*;

/** New-role transition layer. Registration and world executors are separate:
 * a pure strategy passing does not make an unregistered role playable. */
final class NewFiveMechanics {
    static final Set<String> COUNTERS=Set.of("zhezhi_images","zhezhi_insight","zhezhi_selected_slot",
        "zhezhi_selected_air","zhezhi_air_stage","zhezhi_brush_stacks","zhezhi_c3_stacks");
    private static final String[] INPUT_KEYS={"charging","zhezhi_air_stage","zhezhi_after_manifestation","zhezhi_after_basic3",
        "zhezhi_after_herald","zhezhi_after_dodge","zhezhi_images","zhezhi_insight","zhezhi_selected_slot","zhezhi_selected_air"};
    private NewFiveMechanics() { }

    /** Image/insight qualifications are mirrored from the weapon's world ledger,
     * not generated by a claimed input or independently aged by this strategy. */
    static void zhezhi(Transition t,Input input){
        switch(input){
            case BASIC -> {
                if(t.has("zhezhi_after_manifestation")){conjuration(t);break;}
                if(t.context.airborne()){air(t);break;}
                int stage=Math.clamp(t.combo,1,3);combo(t,"",3);
                if(stage==3)t.timer("zhezhi_after_basic3",60);
            }
            case HEAVY_START -> t.timer("charging",1);
            case HEAVY_RELEASE,HEAVY_FULL -> {
                t.clear("charging");
                if(t.context.airborne()||t.has("zhezhi_after_basic3")
                    ||t.has("zhezhi_after_herald")||t.has("zhezhi_after_dodge"))conjuration(t);
                else {t.payStamina(20);t.action("heavy");} // Heavy does not reset the basic cursor.
            }
            case AIR -> air(t);
            case DODGE_COUNTER -> {t.action("dodge_counter");t.timer("zhezhi_after_dodge",60);}
            case PERFECT_DODGE -> t.timer("zhezhi_after_dodge",60);
            case SKILL,SKILL_HOLD -> {
                if(t.time("zhezhi_images")>0){herald(t);break;}
                t.requireCooldown("skill");t.timer("skill",120);
                boolean aerial=input==Input.SKILL_HOLD||t.context.airborne();
                t.action(t.context.airborne()?"skill_air":aerial?"skill_hold":"skill");
                if(t.get("spirit")>=60){
                    t.add("spirit",-60);
                    t.effect(Kind.SPAWN_FIELD,"zhezhi_pair",2,300,Map.of("airborne",aerial?1d:0d));
                }
                t.effect(Kind.GAIN_CONCERTO,"manifestation",8,0);
                t.timer("zhezhi_after_manifestation",60);t.clear("zhezhi_air_stage");chain3(t);
            }
            case LIBERATION -> {
                t.requireCooldown("liberation");t.payEnergy(125);t.timer("liberation",500);
                t.action("liberation");t.timer("zhezhi_inklit",600);
                t.effect(Kind.SPAWN_FIELD,"zhezhi_inklit",1,600);
                t.effect(Kind.GAIN_CONCERTO,"liberation",20,0);
                if(t.original.chain()>=4)t.effect(Kind.BUFF_TEAM,"zhezhi_c4_attack",.20,600);
            }
            case INTRO -> {t.action("intro");t.add("spirit",45);t.effect(Kind.GAIN_CONCERTO,"intro",10,0);}
            case OUTRO -> t.effect(Kind.BUFF_NEXT,"zhezhi_outro",1,280,
                Map.of("glacioAmplification",.20,"skillAmplification",.25,"energyOnEnter",15d,"endsOnSwitch",1d));
            default -> { }
        }
    }
    private static void conjuration(Transition t){
        t.payStamina(15);t.action("heavy_conjuration");
        if(t.get("spirit")>=30){t.add("spirit",-30);t.effect(Kind.SPAWN_FIELD,"zhezhi_middle",1,300,Map.of("airborne",t.context.airborne()?1d:0d));}
        t.clear("zhezhi_after_manifestation");t.clear("zhezhi_after_basic3");
        t.clear("zhezhi_after_herald");t.clear("zhezhi_after_dodge");
    }
    private static void air(Transition t){
        int stage=t.time("zhezhi_air_stage")+1;require(stage<=2,"air_chain_exhausted");
        t.payStamina(stage==1?5:25);t.timer("zhezhi_air_stage",stage);t.action("air_basic_0"+stage);
    }
    private static void herald(Transition t){
        int slot=t.time("zhezhi_selected_slot");require(slot>=1&&slot<=3,"world_crane_selection_required");
        boolean enhanced=t.time("zhezhi_insight")==2;
        t.action(enhanced?"skill_maestro":t.context.airborne()?"skill_genius_air":"skill_genius");
        t.effect(Kind.MOVE_SPECIAL,"zhezhi_crane",1,12,Map.of("slot",(double)slot,"enhanced",enhanced?1d:0d,
            "resetAirDodge",t.time("zhezhi_selected_air")>0?1d:0d));
        t.effect(Kind.GAIN_CONCERTO,"herald",13,0);t.timer("zhezhi_after_herald",60);
        t.clear("zhezhi_air_stage");
        int brush=Math.min(3,t.time("zhezhi_brush_stacks")+1);
        t.timer("zhezhi_brush_stacks",brush);t.timer("zhezhi_brush_life",540);
        t.effect(Kind.BUFF_SELF,"zhezhi_brush_attack",brush*.06,540);
        if(enhanced){
            t.effect(Kind.BUFF_SELF,"zhezhi_maestro_basic",.18,540);
            if(t.original.chain()>=1){t.effect(Kind.GAIN_ENERGY,"zhezhi_c1",15,0);t.effect(Kind.BUFF_SELF,"zhezhi_c1_crit",.10,540);}
        }
        if(t.original.chain()>=6)t.effect(Kind.NATIVE_PROC,"zhezhi_white_crane_c6",1,0);
        chain3(t);
        // World executor consumes and updates the actual ledger atomically; these
        // selection qualifications cannot be reused before its next snapshot.
        t.clear("zhezhi_images");t.clear("zhezhi_insight");t.clear("zhezhi_selected_slot");t.clear("zhezhi_selected_air");
    }
    private static void chain3(Transition t){
        if(t.original.chain()<3)return;
        int stacks=Math.min(3,t.time("zhezhi_c3_stacks")+1);
        t.timer("zhezhi_c3_stacks",stacks);t.timer("zhezhi_c3_life",540);
        t.effect(Kind.BUFF_SELF,"zhezhi_c3_attack",stacks*.15,540);
    }
    static void tick(Transition t){
        if(t.original.characterId().equals("zani")){ZaniMechanics.tick(t);return;}
        if(t.original.characterId().equals("augusta")){AugustaMechanics.tick(t);return;}
        if(t.original.characterId().equals("lucilla")){LucillaMechanics.tick(t);return;}
        if(!t.original.characterId().equals("zhezhi"))return;
        if(!t.context.airborne())t.clear("zhezhi_air_stage");
        if(!t.has("zhezhi_brush_life"))t.clear("zhezhi_brush_stacks");
        if(!t.has("zhezhi_c3_life"))t.clear("zhezhi_c3_stacks");
    }
    static void switchOut(Transition t){
        if(t.original.characterId().equals("suoming")){SuomingMechanics.switchOut(t);return;}
        if(t.original.characterId().equals("zani")){ZaniMechanics.switchOut(t);return;}
        if(t.original.characterId().equals("augusta")){AugustaMechanics.switchOut(t);return;}
        if(t.original.characterId().equals("lucilla")){LucillaMechanics.switchOut(t);return;}
        if(!t.original.characterId().equals("zhezhi"))return;
        for(String key:INPUT_KEYS)t.clear(key);
    }
    static MechanicsState leaveWorld(MechanicsState state){
        // The host discards photo/realm ledgers on a portal transition. End their
        // dependent forms without scheduling a finisher in the destination world.
        // Resources and paid cooldowns remain owned by the same weapon.
        if(state.characterId().equals("lucilla")||state.characterId().equals("augusta")){
            var cleared=InterruptionRules.cancelled(state);
            var timers=new java.util.HashMap<>(cleared.timers());
            if(state.characterId().equals("lucilla")){
                for(String key:Set.of("lucilla_finale_lock","lucilla_forget_serial","lucilla_camera_marker"))timers.remove(key);
            }else{
                for(String key:Set.of("augusta_phase","augusta_realm","augusta_sun_count","augusta_finale",
                    "augusta_spin_window","augusta_upper_window","augusta_skill_upper_window","augusta_skill_link","augusta_skill_stage","augusta_skill_counter"))timers.remove(key);
            }
            return new MechanicsState(state.characterId(),"normal",state.mode(),state.chain(),1,state.resources(),timers);
        }
        var timers=new java.util.HashMap<>(state.timers());
        for(String key:INPUT_KEYS)timers.remove(key);
        timers.remove("zhezhi_inklit");
        return new MechanicsState(state.characterId(),state.form(),state.mode(),state.chain(),1,state.resources(),timers);
    }
}
